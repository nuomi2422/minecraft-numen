package com.dwinovo.numen.plugins.rdd;

import java.util.List;

/**
 * 「题型」——长线目标的**阶段骨架**，注入 Stage-A 规划器（2026-10-27，主人要的「写题型注入规划 AI」）。
 *
 * <h2>为什么需要它（实测缺口）</h2>
 * 2026-10-25 的 6 级链是「拴床绑重生点」这类单点目标拆出来的形状，用得很好；
 * 但「通关MC」这种终局目标，规划器手里**只有句目标正文**——它很容易把 12 个阶段名额
 * 花在开头（木头→木板→木棍→工作台…），等真的需要「下界取烈焰棒」时名额已经用完。
 * 主人 #340 那晚的观察（12 轮 1783 次调用只到 S2 石器）就是同一件事的影子：
 * **不是不努力，是没有"这类目标长什么样"的先验**。
 *
 * <h2>设计纪律</h2>
 * <ul>
 *   <li><b>只给形状，不给数量</b>：骨架列「有哪些阶段」，不指定每阶段几步、不写具体坐标/数量——
 *       具体交给规划器按实况决定（它看得到背包与事实）。</li>
 *   <li><b>只在长线目标时出现</b>：关键词命中才注入，普通目标（造箱子/挖 32 石头）一个 token 都不占。</li>
 *   <li><b>纯文本、可单测</b>：不读世界、不碰 Minecraft。</li>
 *   <li><b>不复述常识</b>：写的是「顺序与出口判据」，不是「木头可以做木板」这种模型本来就会的。</li>
 * </ul>
 */
final class RddStagePatterns {

    private RddStagePatterns() {}

    /** 命中即认为「这是长线终局目标」。刻意窄：宁可漏，不要给普通目标塞长线骨架。 */
    private static final List<String> LONG_HORIZON = List.of(
            "通关", "末影龙", "末地", "beat the game", "beat minecraft", "ender dragon", "终局", "通mc", "打龙");

    /** 这个目标算不算长线终局目标（供测试与调用方判定）。 */
    static boolean isLongHorizon(String objective) {
        if (objective == null || objective.isBlank()) {
            return false;
        }
        String lower = objective.toLowerCase(java.util.Locale.ROOT);
        for (String k : LONG_HORIZON) {
            if (lower.contains(k)) {
                return true;
            }
        }
        return false;
    }

    /**
     * 阶段骨架块（不命中返回空串）。
     *
     * <p>骨架本身是**顺序与出口**，不是清单：每一行都是「这一阶段结束时必须已经成立的事实」。
     * 没有出口判据的阶段会互相吞——这是规划器最容易犯的错，也是阶段数被浪费掉的主因。
     */
    static String block(String objective) {
        if (!isLongHorizon(objective)) {
            return "";
        }
        return "<stage_patterns>\n"
                + "长线终局目标的阶段骨架（只给顺序与出口，不规定每阶段几步；按实况取舍，可合并但不要跳序）：\n"
                + "① 立足：能活下去的最小装备（木→石工具）＋ 食物来源 ＋ 一个绑好的重生点。"
                + "出口：能反复取食且死了能回原地。\n"
                + "② 铁器：挖铁 → 熔炼 → 铁镐铁剑铁甲。出口：能挖钻石的镐与敢下矿的甲。\n"
                + "③ 升级：钻石（铁镐挖，记得带水/垫脚）或下界合金。出口：本阶段最强的工具/甲已在身上。\n"
                + "④ 下界：**先备点火物**（打火石＝燧石＋铁锭，或火焰弹）＋ 黑曜石 10（废墟传送门的框可以直接挖）"
                + " → 造/点亮传送门 → 进下界找堡垒 → 取烈焰棒 → 打末影人收珍珠。"
                + "出口：烈焰棒与珍珠在某处有定量存货。"
                // 2026-10-28 实机：规划器写了「右键烈焰弹点火」，而烈焰弹要**烈焰粉**——
                // 烈焰粉只能在下界拿到，等于"进下界之前要先有下界的东西"=循环依赖。
                // 点火物必须给能自给自足的那一个。
                + "（点火物只能用**打火石**：燧石＋铁锭，两样主世界都有；"
                + "不要用烈焰弹/火焰弹，它要烈焰粉，是循环依赖。）\n"
                // 2026-10-28 实机（#232）：她站在堡垒里（砖 21 格外）、32 格内却没有刷怪笼，
                // 而判据写的是 block_nearby(spawner, r=16) —— 等于要求她恰好站在笼边。
                // 堡垒很大，笼子不一定在门口；所以进堡垒和找笼要分开写、半径要够大。
                + "⑤ 堡垒：进堡垒的判据用 nether_bricks(r=8) 或 structure:fortress（达成了就别回退）；"
                + "找烈焰人另起一步，用 entity_nearby(blaze, r=48) 或 block_nearby(spawner, r=48)，"
                + "不要用 16 格以内的刷怪笼判据——堡垒很大，笼子常常离入口几十格。\n"
                + "⑤ 末地准备：末影之眼（珍珠+烈焰粉）＋ 补给（食物/垫脚/投掷物）。出口：眼睛里已合成、补给按趟数配足。\n"
                + "⑥ 定位：用末影之眼找到要塞 → 走到传送门。出口：站在末地传送门房间。\n"
                + "⑦ 终局：进末地 → 先破水晶 → 再打龙。出口：龙死。\n"
                + "硬规矩：\n"
                + "- 每个阶段必须能写出「什么事实成立 = 这阶段结束」，写不出的阶段会和下一个搅在一起；\n"
                + "- 阶段数不够时，把**低风险、可合并**的（如 ①②）合并，不要砍 ④⑤⑥；\n"
                + "- 同一阶段内如果一条路反复失败，换来源/换材料/换顺序，不要在原路上加码。\n"
                + "</stage_patterns>";
    }
}
